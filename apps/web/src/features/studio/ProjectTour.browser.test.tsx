import { expect, it, vi } from "vite-plus/test";
import { userEvent } from "vite-plus/test/browser";
import { render } from "../../../test/render";
import { randomUUID } from "../../lib/randomUUID";
import StudioWorkspace from "./StudioWorkspace";
import { listDrafts } from "./drafts";

it("resumes guidance for the same project without changing sheets, edits, approvals or agent state", async () => {
  const workspaceId = randomUUID();
  const onAskAgent = vi.fn(async () => {});
  await using screen = await render(<StudioWorkspace workspaceId={workspaceId} onAskAgent={onAskAgent} />, { router: false });
  const button = (name: string | RegExp) => screen.getByRole("button", { name, exact: typeof name === "string" });
  await button(/^Affiliate Storefront/).click();
  await screen.getByRole("textbox", { name: "Project name" }).fill("Desk lamps");
  await expect.element(screen.getByText("Saved on this device", { exact: true })).toBeVisible();
  const before = await listDrafts(workspaceId);
  await button("Quick tour").click();
  await expect.element(screen.getByRole("heading", { name: "Name this project" })).toHaveFocus();
  await button("Next tip").click();
  const selector = screen.getByRole("combobox", { name: "Go to step" }).element() as HTMLSelectElement;
  selector.focus();
  expect(document.activeElement).toBe(selector);
  await userEvent.keyboard("{Escape}");
  await expect.element(button("Resume tour")).toHaveFocus();
  await button("Projects").click();
  await button(/^Desk lamps/).click();
  await button("Resume tour").click();
  await expect.element(screen.getByRole("heading", { name: "Move between sheets" })).toBeVisible();
  await button("Next tip").click();
  await expect.element(screen.getByText(/merchant-issued affiliate links/)).toBeVisible();
  await button("Finish tour").click();
  expect(await listDrafts(workspaceId)).toEqual(before);
  expect(onAskAgent).not.toHaveBeenCalled();
  await expect.element(button("Quick tour")).toHaveFocus();
  await button("Projects").click();
  await button("New project").click();
  await button(/^Blank/).click();
  await button("Quick tour").click();
  await button("Next tip").click();
  await expect.element(screen.getByRole("heading", { name: "Write on this sheet" })).toBeVisible();
  await button("Pause tour").click();
});
